/**
 * Storage abstraction for uploaded media.
 *
 * CMS business logic depends only on this interface, never on a provider SDK.
 * The local filesystem adapter serves development, and an S3-compatible adapter
 * serves production. Binary files are never stored in PostgreSQL; the database
 * keeps metadata and the object key only.
 */

export type StorageObjectInput = {
  /** Provider-relative key. Already validated and sanitized by the caller. */
  key: string;
  body: Uint8Array;
  contentType: string;
};

export type StoredObject = {
  key: string;
  sizeBytes: number;
  contentType: string;
  /** Browser-reachable URL, or `null` when the provider cannot expose one safely. */
  publicUrl: string | null;
};

export type StorageReadResult = {
  body: Uint8Array;
  contentType: string;
};

export interface StorageProvider {
  readonly name: "local" | "s3";
  upload(input: StorageObjectInput): Promise<StoredObject>;
  delete(key: string): Promise<void>;
  /** Returns a public URL only when the provider can build a safe one. */
  getPublicUrl(key: string): string | null;
  exists(key: string): Promise<boolean>;
  /** Reads bytes back for server-side previews or local serving. */
  read(key: string): Promise<StorageReadResult | null>;
}

/** Raised when a key would escape the configured storage root or bucket prefix. */
export class StorageKeyError extends Error {
  constructor(message = "Invalid storage key.") {
    super(message);
    this.name = "StorageKeyError";
  }
}

/**
 * Validates a provider-relative object key.
 *
 * Rejects absolute paths, `..` traversal, backslashes, control characters, and
 * dot-only segments. Keys are generated by the application, but this still runs
 * on every read/write so a malformed database value cannot escape storage.
 */
export function assertSafeStorageKey(key: string): string {
  if (!key || key.length > 300) {
    throw new StorageKeyError();
  }

  if (/[\u0000-\u001f\\]/.test(key)) {
    throw new StorageKeyError();
  }

  if (key.startsWith("/") || key.includes("..") || key.includes("//")) {
    throw new StorageKeyError();
  }

  const segments = key.split("/");

  if (segments.some((segment) => segment.length === 0 || segment === "." || segment === "..")) {
    throw new StorageKeyError();
  }

  if (!/^[A-Za-z0-9._/-]+$/.test(key)) {
    throw new StorageKeyError();
  }

  return key;
}
