import "server-only";

import { Algorithm, hash, parseOptions, verify } from "@node-rs/argon2";

import { PASSWORD_MAX_LENGTH, PASSWORD_MIN_LENGTH } from "./password-policy";

export { PASSWORD_MAX_LENGTH, PASSWORD_MIN_LENGTH };

/**
 * Argon2id password hashing.
 *
 * Parameters follow the OWASP Password Storage Cheat Sheet baseline for
 * Argon2id and were benchmarked on the owner's development workstation
 * (Windows, Node.js 26.13.0): `m=19456 KiB, t=2, p=1` costs ~22 ms per hash, so
 * a login attempt cannot be amplified into a cheap CPU/DoS vector while still
 * being expensive for an offline attacker.
 *
 * Every hash is self-describing (PHC string:
 * `$argon2id$v=19$m=...,t=...,p=...$salt$digest`), so raising the parameters
 * later does not invalidate existing hashes. `needsRehash()` detects that case
 * and the login flow transparently rehashes on the next successful sign-in.
 *
 * Salt: 16 cryptographically random bytes generated by the native library per
 * hash, so two identical passwords never share a digest.
 */
export type Argon2idParameters = {
  algorithm: Algorithm;
  memoryCost: number;
  timeCost: number;
  parallelism: number;
  outputLen: number;
};

// `Algorithm` is declared as a TypeScript const enum by the native package;
// use its stable numeric Argon2id value (2) here so `isolatedModules` remains
// compatible while the native implementation still receives Argon2id.
export const ARGON2ID_PARAMETERS: Argon2idParameters = {
  algorithm: 2 as Algorithm,
  memoryCost: 19_456,
  timeCost: 2,
  parallelism: 1,
  outputLen: 32,
};

export type PasswordHashOptions = Partial<Argon2idParameters>;

/**
 * Precomputed Argon2id hash of an unrelated sentinel string, never a real
 * password. Credential verification runs against this value when no account
 * matches, so an unknown email costs the same verification time as a known one
 * and account existence is not observable through response timing.
 */
export const DUMMY_PASSWORD_HASH =
  "$argon2id$v=19$m=19456,t=2,p=1$dcW4RNc0YsQ17jbZ4GvA6g$ZZ2pGQEIm3EVox4n0fja+5w1c94JNL9MgiX1wycKixE";

/**
 * Returns a human-readable reason when a candidate password is unacceptable,
 * or `null` when it passes the administrator password policy.
 *
 * Policy: at least 8 characters, at most 256, and not only whitespace. Length
 * is the property that actually resists offline cracking; composition rules are
 * deliberately not imposed beyond base character variety.
 */
export function checkPasswordPolicy(password: unknown): string | null {
  if (typeof password !== "string") {
    return "Password must be a string.";
  }

  if (password.trim().length === 0) {
    return "Password cannot be blank.";
  }

  if (password.length < PASSWORD_MIN_LENGTH) {
    return `Password must be at least ${PASSWORD_MIN_LENGTH} characters.`;
  }

  if (password.length > PASSWORD_MAX_LENGTH) {
    return `Password must be at most ${PASSWORD_MAX_LENGTH} characters.`;
  }

  return null;
}

/**
 * Hashes a password with Argon2id. Rejects invalid input instead of hashing
 * something unexpected; the plaintext is never logged or returned anywhere.
 */
export async function hashPassword(
  password: string,
  options: PasswordHashOptions = {},
): Promise<string> {
  const policyError = checkPasswordPolicy(password);

  if (policyError) {
    throw new TypeError(policyError);
  }

  return hash(password, { ...ARGON2ID_PARAMETERS, ...options });
}

/**
 * Verifies a password against a stored hash.
 *
 * Returns `false` — never throws — for a malformed hash or a wrong password, so
 * callers cannot distinguish "no such account" from "wrong password" through
 * error behaviour. Comparison is performed by the Argon2 implementation, which
 * compares the derived digests in constant time.
 */
export async function verifyPassword(
  storedHash: string | null | undefined,
  password: string,
): Promise<boolean> {
  if (typeof storedHash !== "string" || storedHash.length === 0) {
    return false;
  }

  if (typeof password !== "string" || password.length === 0) {
    return false;
  }

  try {
    return await verify(storedHash, password);
  } catch {
    return false;
  }
}

/**
 * True when a stored hash was produced with weaker/different parameters than
 * the current policy and should be replaced after a successful verification.
 */
export function needsRehash(storedHash: string | null | undefined): boolean {
  if (typeof storedHash !== "string" || storedHash.length === 0) {
    return true;
  }

  try {
    const parsed = parseOptions(storedHash);

    return (
      parsed.algorithm !== ARGON2ID_PARAMETERS.algorithm ||
      parsed.memoryCost !== ARGON2ID_PARAMETERS.memoryCost ||
      parsed.timeCost !== ARGON2ID_PARAMETERS.timeCost ||
      parsed.parallelism !== ARGON2ID_PARAMETERS.parallelism ||
      parsed.outputLen !== ARGON2ID_PARAMETERS.outputLen
    );
  } catch {
    return true;
  }
}
